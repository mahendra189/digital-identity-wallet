import React, { useState } from 'react';
import { Card, CardHeader, CardTitle, CardDescription, CardContent, CardFooter } from '../components/ui/card';
import { Button } from '../components/ui/button';
import { Label } from '../components/ui/label';
import { claimCredentialFromOffer } from '../services/openid4vci';
import { saveCredential } from '../services/storage';
import { SDJWTCredential } from '../types/campusId';
import { ArrowLeft, AlertCircle, KeyRound, Sparkles } from 'lucide-react';

interface ClaimPageProps {
  onNavigate: (route: string) => void;
  onClaimSuccess: (cred: SDJWTCredential) => void;
  onNotification: (msg: string) => void;
}

export const ClaimPage: React.FC<ClaimPageProps> = ({
  onNavigate,
  onClaimSuccess,
  onNotification,
}) => {
  const [offerInput, setOfferInput] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const handleClaim = async (uriToClaim?: string) => {
    const target = (uriToClaim || offerInput).trim();
    if (!target) {
      setError('Please enter or paste an OpenID4VCI credential offer.');
      return;
    }

    setError(null);
    setIsLoading(true);
    try {
      const cred = await claimCredentialFromOffer(target);
      await saveCredential(cred);
      onClaimSuccess(cred);
      onNotification(`🎉 Successfully claimed ${cred.claims.name}'s ID (${cred.id})!`);
      onNavigate('/');
    } catch (err: any) {
      setError(err.message || 'Credential issuance failed.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleQuickDemo = async () => {
    setIsLoading(true);
    setError(null);
    try {
      const resp = await fetch('http://localhost:8000/api/v1/issuer/token', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          grant_type: 'urn:ietf:params:oauth:grant-type:pre-authorized_code',
          pre_authorized_code: 'demo_code',
        }),
      }).catch(() => null);

      if (resp && resp.ok) {
        await handleClaim(
          'openid-credential-offer://?credential_issuer=http://localhost:8000&pre-authorized_code=demo_code'
        );
      } else {
        setError('Backend is not reachable on http://localhost:8000. Please start your backend first.');
      }
    } catch (err: any) {
      setError(err.message || 'Quick demo failed.');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="max-w-2xl mx-auto px-4 py-8 space-y-6">
      <div className="flex items-center gap-3">
        <Button variant="ghost" size="sm" onClick={() => onNavigate('/')} className="size-8 p-0">
          <ArrowLeft className="size-4" />
        </Button>
        <div>
          <h1 className="text-xl font-bold tracking-tight text-zinc-900">Claim Credential</h1>
          <p className="text-xs text-zinc-500">Receive and bind an authentic OpenID4VCI credential to your hardware key</p>
        </div>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="text-base">Enter Credential Offer</CardTitle>
          <CardDescription>
            Paste the OpenID4VCI offer URI generated by the Campus Admin Portal or click quick demo.
          </CardDescription>
        </CardHeader>

        <CardContent className="space-y-4">
          {error && (
            <div className="p-3 rounded-md bg-red-50 border border-red-200 text-xs text-red-700 flex items-start gap-2">
              <AlertCircle className="size-4 shrink-0 mt-0.5" />
              <span>{error}</span>
            </div>
          )}

          <div className="space-y-2">
            <Label htmlFor="offerInput">Credential Offer URI</Label>
            <textarea
              id="offerInput"
              rows={3}
              value={offerInput}
              onChange={(e) => setOfferInput(e.target.value)}
              placeholder="openid-credential-offer://?credential_offer=..."
              className="w-full rounded-md border border-zinc-200 bg-white p-3 text-xs font-mono text-zinc-900 placeholder:text-zinc-400 focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-zinc-950"
            />
          </div>

          <div className="p-3 rounded-md bg-zinc-50 border border-zinc-200 text-xs text-zinc-600 space-y-1">
            <div className="flex items-center gap-1.5 font-medium text-zinc-900">
              <KeyRound className="size-3.5" /> Cryptographic Key Binding
            </div>
            <p className="text-zinc-500 leading-relaxed">
              When claiming, your wallet signs a Proof-of-Possession JWT with its Web Crypto P-256 private key. The issuer binds your public key into the SD-JWT credential (`cnf.jwk`).
            </p>
          </div>
        </CardContent>

        <CardFooter className="flex flex-col sm:flex-row items-center justify-between gap-3 pt-4 border-t border-zinc-100">
          <Button variant="outline" size="sm" onClick={handleQuickDemo} disabled={isLoading} className="w-full sm:w-auto">
            <Sparkles className="size-3.5 mr-1" />
            Issue local demo pass
          </Button>

          <Button size="sm" onClick={() => handleClaim()} disabled={isLoading || !offerInput.trim()} className="w-full sm:w-auto">
            {isLoading ? 'Claiming Credential...' : 'Claim Credential'}
          </Button>
        </CardFooter>
      </Card>
    </div>
  );
};
